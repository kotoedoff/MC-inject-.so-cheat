#!/usr/bin/env python3
# Generates src/font.h from a PSF1 console font with a unicode table
# (default: /usr/share/consolefonts/Uni1-VGA8.psf.gz — 8x8, 512 glyphs, Cyrillic incl.).
# Output: 8x8 bitmaps, own compact index space:
#   0..127   ASCII
#   128..159 A-YA (U+0410..U+042F)
#   160..191 a-ya (U+0430..U+044F)
#   192      Yo (U+0401), 193 yo (U+0451)
#   ?        anything else
import gzip, sys, struct

SRC = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/consolefonts/Uni1-VGA8.psf.gz"
OUT = sys.argv[2] if len(sys.argv) > 2 else "src/font.h"

def load_psf1(path):
    op = gzip.open if path.endswith(".gz") else open
    d = op(path, "rb").read()
    assert d[:2] == b"\x36\x04", "not psf1"
    mode = d[2]
    charsize = d[3]          # bytes per glyph == height
    count = 512 if (mode & 1) else 256
    glyphs = d[4:4 + count * charsize]
    # unicode table: per glyph, UCS2 LE values until 0xFFFF; 0xFFFE starts a sequence
    table = [set() for _ in range(count)]
    pos = 4 + count * charsize
    if mode & 2:
        g = 0
        while g < count and pos + 2 <= len(d):
            v = struct.unpack("<H", d[pos:pos+2])[0]
            pos += 2
            if v == 0xFFFF:
                g += 1
                continue
            if v != 0xFFFE:
                table[g].add(v)
    return charsize, count, glyphs, table

def local_index(cp):
    if 0x20 <= cp <= 0x7E: return cp
    if 0x410 <= cp <= 0x42F: return 128 + (cp - 0x410)
    if 0x430 <= cp <= 0x44F: return 160 + (cp - 0x430)
    if cp == 0x401: return 192
    if cp == 0x451: return 193
    return None

charsize, count, glyphs, table = load_psf1(SRC)
nglyph = 194
rows = [[0]*8 for _ in range(nglyph)]
for g in range(count):
    idxs = set()
    for cp in table[g]:
        li = local_index(cp)
        if li is not None: idxs.add(li)
    if not idxs: continue
    bitmap = glyphs[g*charsize:(g+1)*charsize]
    for li in idxs:
        for y in range(min(charsize, 8)):
            rows[li][y] |= bitmap[y]

# space -> blank, '?' fallback for empty slots
for li in range(nglyph):
    if all(b == 0 for b in rows[li]) and li != 0x20:
        rows[li] = rows[0x3F][:]  # copy '?'

with open(OUT, "w") as f:
    f.write("// AUTO-GENERATED by tools/mkfont.py from %s — do not edit\n" % SRC)
    f.write("#pragma once\n#include <cstdint>\n\n")
    f.write("namespace voltage { namespace font {\n")
    f.write("constexpr int kGlyphW = 8, kGlyphH = 8, kGlyphs = %d;\n" % nglyph)
    f.write("// glyph rows, 1 bit per pixel (MSB = leftmost)\n")
    f.write("inline const uint8_t kBitmap[%d][8] = {\n" % nglyph)
    for li in range(nglyph):
        f.write("  {" + ",".join("0x%02x" % b for b in rows[li]) + "},")
        f.write("\n")
    f.write("};\n")
    f.write("} }\n")
print("wrote %s: %d glyphs (ASCII + Cyrillic)" % (OUT, nglyph))
